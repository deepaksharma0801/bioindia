"""Draw the dashboard's clickable state map (#indiaMap) from the real state boundaries in PostGIS.

Replaces the contents of the <svg id="indiaMap"> element in BioIndia_v3_Complete.html with one path per
state or union territory (geoBoundaries ADM1, simplified), in an equirectangular projection scaled by
cos(22°) so India keeps its true shape. Each path keeps class "sp" and data-state, which the dashboard's
click handlers use.

Usage: python scripts/build_state_map.py
"""

from __future__ import annotations

import json
import math
import os
import re
from html import escape
from pathlib import Path

import psycopg


ROOT = Path(__file__).resolve().parents[1]
HTML = ROOT / "BioIndia_v3_Complete.html"
DATABASE_URL = os.environ.get("DATABASE_URL", "postgresql://bioindia:bioindia@127.0.0.1:5432/bioindia")

WEST, EAST, SOUTH, NORTH = 68.0, 97.5, 6.5, 37.2
WIDTH = 600
SCALE_X = math.cos(math.radians(22))
HEIGHT = round(WIDTH * (NORTH - SOUTH) / ((EAST - WEST) * SCALE_X))
SIMPLIFY_DEGREES = 0.02
MIN_LABEL_AREA_KM2 = 75_000  # label only the larger states; small ones show their name on hover
SHORT_LABELS = {"Uttar Pradesh": "UP", "Madhya Pradesh": "MP", "Andhra Pradesh": "Andhra", "Arunachal Pradesh": "Arunachal"}


def project(lon: float, lat: float) -> tuple[float, float]:
    return (lon - WEST) / (EAST - WEST) * WIDTH, (NORTH - lat) / (NORTH - SOUTH) * HEIGHT


def ring_path(ring: list[list[float]]) -> str:
    points = [project(lon, lat) for lon, lat in ring]
    return "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in points) + "Z"


def main() -> None:
    with psycopg.connect(DATABASE_URL) as connection:
        rows = connection.execute(
            """SELECT state, ST_AsGeoJSON(ST_SimplifyPreserveTopology(geom, %s), 3),
                      ST_X(ST_PointOnSurface(geom)), ST_Y(ST_PointOnSurface(geom)), ST_Area(geom::geography) / 1e6
               FROM reference_states ORDER BY ST_Area(geom) DESC""", (SIMPLIFY_DEGREES,)).fetchall()

    paths, labels = [], []
    for state, geojson, label_lon, label_lat, area_km2 in rows:
        geometry = json.loads(geojson)
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        d = "".join(ring_path(ring) for polygon in polygons for ring in polygon if len(ring) >= 4)
        paths.append(f'<path class="sp" data-state="{escape(state)}" d="{d}"><title>{escape(state)}</title></path>')
        if area_km2 >= MIN_LABEL_AREA_KM2:
            x, y = project(label_lon, label_lat)
            labels.append(f'<text x="{x:.0f}" y="{y:.0f}" font-size="7" text-anchor="middle" fill="rgba(168,196,216,0.45)" '
                          f'font-family="Cinzel,serif" pointer-events="none">{escape(SHORT_LABELS.get(state, state))}</text>')

    inner = ("\n          <!-- Generated by scripts/build_state_map.py from geoBoundaries ADM1 (CC BY 2.5 IN). -->\n          "
             + "\n          ".join(paths + labels) + "\n        ")
    html = HTML.read_text(encoding="utf-8")
    pattern = re.compile(r'(<svg class="india-map-svg" id="indiaMap") viewBox="[^"]*"( xmlns="http://www.w3.org/2000/svg">).*?(</svg>)', re.S)
    html, count = pattern.subn(lambda m: f'{m.group(1)} viewBox="0 0 {WIDTH} {HEIGHT}"{m.group(2)}{inner}{m.group(3)}', html, count=1)
    if count != 1:
        raise SystemExit("Could not find the #indiaMap SVG in the dashboard HTML.")
    HTML.write_text(html, encoding="utf-8")
    print(f"Wrote {len(paths)} state paths ({len(labels)} labelled) into #indiaMap, viewBox 0 0 {WIDTH} {HEIGHT}")


if __name__ == "__main__":
    main()
